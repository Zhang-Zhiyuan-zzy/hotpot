@pytest.mark.parametrize(("module_name", "expected"), _PUBLIC_EXPORTS.items())
def test_scientific_state_exports_match_the_approved_split(module_name, expected):
    module = import_module(module_name)
    assert tuple(module.__all__) == expected
    assert all(hasattr(module, name) for name in expected)


@pytest.mark.parametrize(("name", "owner"), _ENTRY_OWNERS.items())
def test_calculation_entries_reexport_the_one_actual_owner(name, owner):
    entry = getattr(import_module(
        "hotpot.cheminfo.operations.calculation.scientific_state"
    ), name)
    assert entry is getattr(import_module(owner), name)
    assert entry.__module__ == owner
