def _element_equivalence_cases() -> Tuple[DifferentialCase, ...]:
    cases = []
    for atomic_number, symbol in enumerate(ELEMENT_SYMBOLS, start=1):
        key = f"element.{atomic_number:03d}.{symbol}"
        target = f"[{symbol}]"
        common = {
            "smiles": target,
            "group": "element_equivalence",
            "expected_matched": True,
            "compare_enumeration": True,
            "evidence_tier": "tier_1_periodic_identity",
            "equivalence_key": key,
        }
        cases.append(
            DifferentialCase(
                case_id=f"matrix.{key}.atomic_number",
                smarts=f"[#{atomic_number}]",
                features=("element_matrix", "atomic_number"),
                equivalence_variant="atomic_number",
                **common,
            )
        )
        cases.append(
            DifferentialCase(
                case_id=f"matrix.{key}.symbol",
                smarts=target,
                features=("element_matrix", "element_symbol"),
                equivalence_variant="symbol",
                **common,
            )
        )
    return tuple(cases)


CASES += _element_equivalence_cases()
