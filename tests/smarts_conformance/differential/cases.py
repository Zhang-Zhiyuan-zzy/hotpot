    case_id: str
    smarts: str
    smiles: str
    group: str
    expected_matched: Optional[bool]
    compare_enumeration: bool
    features: Tuple[str, ...]
    evidence_tier: str
    notes: str = ""
    expected_query_accepted: Optional[bool] = True
    equivalence_key: Optional[str] = None
    equivalence_variant: Optional[str] = None


